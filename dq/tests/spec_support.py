"""Parser, validator, and tracker renderer for SPEC documents (SPEC-008).

The spec file is the single source of truth for a piece of work: its status
and its per-gate progress live in the file. ``docs/roadmap.adoc`` carries a
tracker table that is *derived* from the spec files by
``scripts/roadmap.py`` and checked by ``test_specs_contract.py``, so the
two can never disagree for long.

This module is pure stdlib and reads only the working tree, so the contract
test needs nothing installed beyond the package's own dependencies.
"""

from __future__ import annotations

import dataclasses
import re
from dataclasses import dataclass
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
SPECS_DIR = REPOSITORY_ROOT / "docs" / "specs"
ROADMAP_PATH = REPOSITORY_ROOT / "docs" / "roadmap.adoc"
ADR_DIR = REPOSITORY_ROOT / "docs" / "decisions" / "adr"
CHANGELOG_PATH = REPOSITORY_ROOT / "CHANGELOG.md"

#: The status vocabulary, in lifecycle order, then the terminal states.
STATUSES = (
    "Proposed",
    "Accepted",
    "In Progress",
    "Verified",
    "Released",
    "Blocked",
    "Deferred",
    "Superseded",
    "Rejected",
)

#: Statuses at which every gate must be checked and carry evidence.
COMPLETE_STATUSES = frozenset({"Verified", "Released"})
#: Statuses at which at least one gate must be checked.
STARTED_STATUSES = frozenset({"In Progress", "Verified", "Released"})
#: Statuses that must state why on the status line.
REASONED_STATUSES = frozenset({"Blocked", "Deferred", "Superseded", "Rejected"})

REQUIRED_SECTIONS = (
    "Purpose",
    "In scope",
    "Out of scope",
    "Acceptance gates",
    "Progress",
)
REQUIRED_FIELDS = ("Status", "Date", "Driven by", "Milestone")
MILESTONES = tuple(f"M{index}" for index in range(6)) + ("Shipped", "None")

_TABLE_START = "// roadmap:table-start (generated by scripts/roadmap.py --write)"
_TABLE_END = "// roadmap:table-end"

_SPEC_TITLE = re.compile(r"^= (SPEC-(\d+)): (.+)$")
_SECTION = re.compile(r"^== (.+)$")
_FIELD = re.compile(r"^([A-Z][A-Za-z ]+): (.*)$")
_GATE = re.compile(r"^\* +(G\d+) +[—–-]+ +(.*)$")
_PROGRESS = re.compile(r"^\* +\[( |x|X)\] +(G\d+) +[—–-]+ +(.*)$")
_LIST_ITEM = re.compile(r"^[*.] +")
_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_ADR_REF = re.compile(r"\bADR-(\d{3})\b")
_SPEC_REF = re.compile(r"\bSPEC-(\d{3})\b")
_RELEASE_IN_STATUS = re.compile(r"^Released +[—–-]+ +v?(\d+\.\d+\.\d+)")
_CHANGELOG_VERSION = re.compile(r"^## \[(\d+\.\d+\.\d+)\]", re.MULTILINE)


@dataclass(frozen=True)
class Gate:
    """One acceptance gate: a stable ID and what must be true."""

    id: str
    text: str


@dataclass(frozen=True)
class Spec:
    """A parsed SPEC document."""

    number: int
    path: Path
    title: str
    fields: dict
    sections: dict
    gates: tuple
    progress: tuple  # (checked: bool, gate_id: str, text: str)
    links: str

    @property
    def id(self) -> str:
        return f"SPEC-{self.number:03d}"

    @property
    def status(self) -> str:
        return _status_value(self.fields.get("Status", ""))

    @property
    def status_note(self) -> str:
        value = self.fields.get("Status", "").strip()
        for separator in (" — ", " – ", " - "):
            if separator in value:
                return value.split(separator, 1)[1].strip()
        return ""

    @property
    def milestone(self) -> str:
        return self.fields.get("Milestone", "").strip()

    @property
    def gates_done(self) -> int:
        return sum(1 for checked, _, _ in self.progress if checked)

    @property
    def filename(self) -> str:
        return self.path.name


def _status_value(raw: str) -> str:
    for separator in (" — ", " – ", " - "):
        raw = raw.split(separator, 1)[0]
    return raw.strip()


def _split_fields(lines):
    fields = {}
    current = None
    for raw in lines:
        line = raw.rstrip()
        if line.endswith("+"):  # AsciiDoc hard line break
            line = line[:-1].rstrip()
        if not line.strip():
            continue
        match = _FIELD.match(line)
        if match and not line.startswith(" "):
            current = match.group(1)
            fields[current] = match.group(2).strip()
        elif current is not None and line.startswith(" "):
            fields[current] = f"{fields[current]} {line.strip()}".strip()
    return fields


def _bullets(lines, pattern):
    """Collect top-level bullets matching ``pattern`` with continuations.

    Each bullet is the pattern's capture groups, in order; an indented
    continuation line is appended to the last group.
    """
    found = []
    current = None
    for line in lines:
        match = pattern.match(line)
        if match:
            current = [group.strip() for group in match.groups()]
            found.append(current)
        elif _LIST_ITEM.match(line) or line.startswith("="):
            current = None
        elif current is not None and line.startswith("  ") and line.strip():
            current[-1] = f"{current[-1]} {line.strip()}"
    return found


def parse_spec(path) -> Spec:
    """Parse one spec document.

    Raises:
        ValueError: When the document has no SPEC title or no sections.
    """
    path = Path(path)
    lines = path.read_text(encoding="utf-8").split("\n")
    title = _SPEC_TITLE.match(lines[0]) if lines else None
    if title is None:
        raise ValueError(f"{path.name}: first line must be '= SPEC-NNN: Title'")
    first_section = next(
        (index for index, line in enumerate(lines) if _SECTION.match(line)), None
    )
    if first_section is None:
        raise ValueError(f"{path.name}: has no '== ' sections")
    fields = _split_fields(lines[1:first_section])

    sections = {}
    links = ""
    current = None
    for line in lines[first_section:]:
        if line.startswith("Links:"):
            links = line[len("Links:") :].strip()
            current = None
            continue
        heading = _SECTION.match(line)
        if heading:
            current = heading.group(1).strip()
            sections[current] = []
            continue
        if current is not None:
            sections[current].append(line)

    gates = tuple(
        Gate(gate_id, text)
        for gate_id, text in _bullets(sections.get("Acceptance gates", []), _GATE)
    )
    progress = tuple(
        (checked.lower() == "x", gate_id, text)
        for checked, gate_id, text in _bullets(sections.get("Progress", []), _PROGRESS)
    )
    return Spec(
        number=int(title.group(2)),
        path=path,
        title=title.group(3).strip(),
        fields=fields,
        sections={name: "\n".join(body).strip() for name, body in sections.items()},
        gates=gates,
        progress=progress,
        links=links,
    )


def load_specs(directory=SPECS_DIR):
    """Parse every spec document, ordered by number."""
    return tuple(
        sorted(
            (parse_spec(path) for path in Path(directory).glob("SPEC-*.adoc")),
            key=lambda spec: spec.number,
        )
    )


def changelog_versions(path=CHANGELOG_PATH):
    """Release versions that have a heading in the changelog."""
    return set(_CHANGELOG_VERSION.findall(Path(path).read_text(encoding="utf-8")))


def existing_adr_numbers(directory=ADR_DIR):
    return {
        int(match)
        for path in Path(directory).glob("ADR-*.adoc")
        for match in re.findall(r"ADR-(\d{3})", path.name)
    }


# ------------------------------------------------------------------ validation


def spec_problems(spec, spec_numbers, adr_numbers, released_versions):
    """Return the contract violations of one spec document.

    Args:
        spec: The parsed spec.
        spec_numbers: Numbers of every spec that exists.
        adr_numbers: Numbers of every ADR that exists.
        released_versions: Versions with a changelog heading.
    """
    problems = []
    if f"SPEC-{spec.number:03d}" not in spec.path.name:
        problems.append(f"{spec.filename}: title ID does not match the file name")
    if spec.status not in STATUSES:
        problems.append(f"{spec.id}: unknown status {spec.status!r}")
    for field in REQUIRED_FIELDS:
        if not spec.fields.get(field, "").strip():
            problems.append(f"{spec.id}: missing header field {field!r}")
    if not _DATE.match(spec.fields.get("Date", "").strip()):
        problems.append(f"{spec.id}: Date must be YYYY-MM-DD")
    if spec.milestone not in MILESTONES:
        problems.append(f"{spec.id}: Milestone must be one of {MILESTONES}")
    if not spec.links:
        problems.append(f"{spec.id}: missing the trailing 'Links:' line")

    for section in REQUIRED_SECTIONS:
        if not spec.sections.get(section, "").strip():
            problems.append(f"{spec.id}: missing or empty section {section!r}")
    if spec.links and all(word not in spec.links for word in ("ADR", "SPEC")):
        problems.append(f"{spec.id}: Links must reference an ADR or a SPEC")

    gate_ids = [gate.id for gate in spec.gates]
    if not gate_ids:
        problems.append(f"{spec.id}: Acceptance gates has no 'G1'-style bullets")
    expected = [f"G{index}" for index in range(1, len(gate_ids) + 1)]
    if gate_ids != expected:
        problems.append(
            f"{spec.id}: gate IDs must be unique and contiguous from G1, got {gate_ids}"
        )

    known = set(gate_ids)
    seen = []
    for checked, gate_id, text in spec.progress:
        if gate_id not in known:
            problems.append(f"{spec.id}: Progress cites unknown gate {gate_id}")
        if gate_id in seen:
            problems.append(f"{spec.id}: Progress lists gate {gate_id} twice")
        seen.append(gate_id)
        if spec.status not in COMPLETE_STATUSES:
            continue
        if not checked:
            # A progress line that exists but is unchecked must not let a
            # spec claim Verified.
            problems.append(
                f"{spec.id}: {spec.status} requires gate {gate_id} to be checked"
            )
        elif "evidence:" not in text.lower():
            problems.append(
                f"{spec.id}: {spec.status} requires an 'evidence:' citation on {gate_id}"
            )
    if spec.status in COMPLETE_STATUSES and set(seen) != known:
        problems.append(
            f"{spec.id}: {spec.status} requires a Progress line for every gate"
        )
    if spec.status in STARTED_STATUSES and not any(
        checked for checked, _, _ in spec.progress
    ):
        problems.append(f"{spec.id}: {spec.status} requires at least one checked gate")
    if spec.status in REASONED_STATUSES and not spec.status_note:
        problems.append(f"{spec.id}: {spec.status} must state why on the Status line")

    if spec.status == "Released":
        match = _RELEASE_IN_STATUS.match(spec.fields.get("Status", "").strip())
        if match is None:
            problems.append(f"{spec.id}: Released requires 'Released — X.Y.Z'")
        elif match.group(1) not in released_versions:
            problems.append(
                f"{spec.id}: release {match.group(1)} has no heading in CHANGELOG.md"
            )

    text = spec.path.read_text(encoding="utf-8")
    for number in _ADR_REF.findall(text):
        if int(number) not in adr_numbers:
            problems.append(f"{spec.id}: references missing ADR-{number}")
    for number in _SPEC_REF.findall(text):
        if int(number) != spec.number and int(number) not in spec_numbers:
            problems.append(f"{spec.id}: references missing SPEC-{number}")
    return problems


def specs_problems(
    specs, directory=SPECS_DIR, adr_numbers=None, released_versions=None
):
    """Validate the whole spec set and each document in it."""
    adr_numbers = existing_adr_numbers() if adr_numbers is None else adr_numbers
    released_versions = (
        changelog_versions() if released_versions is None else released_versions
    )
    numbers = [spec.number for spec in specs]
    problems = []
    if sorted(numbers) != list(range(1, len(numbers) + 1)):
        problems.append(
            f"spec IDs must be unique and contiguous from 001, got {numbers}"
        )
    for spec in specs:
        problems.extend(
            spec_problems(spec, set(numbers), adr_numbers, released_versions)
        )
    for path in Path(directory).glob("SPEC-*.adoc"):
        if not re.match(r"SPEC-\d{3}-[a-z0-9-]+\.adoc$", path.name):
            problems.append(f"{path.name}: file name must be SPEC-NNN-lower-slug.adoc")
    return problems


# --------------------------------------------------------------------- tracker


def render_tracker(specs) -> str:
    """Render the tracker table rows for ``docs/roadmap.adoc``."""
    rows = [
        '[cols="1,4,1,2,1,3",options="header"]',
        "|===",
        "| ID | Spec | Milestone | Status | Gates | Note",
        "",
    ]
    for spec in specs:
        gates = f"{spec.gates_done}/{len(spec.gates)}"
        note = spec.status_note.replace("|", "/")
        rows.append(f"| {spec.id}")
        rows.append(f"| link:specs/{spec.filename}[{spec.title}]")
        rows.append(f"| {spec.milestone}")
        rows.append(f"| {spec.status}")
        rows.append(f"| {gates}")
        rows.append(f"| {note}")
        rows.append("")
    rows.append("|===")
    return "\n".join(rows)


_SUMMARY_START = "// roadmap:summary-start (generated by scripts/roadmap.py --write)"
_SUMMARY_END = "// roadmap:summary-end"


def _milestone_order(milestone):
    if milestone in MILESTONES:
        return (0, MILESTONES.index(milestone))
    return (1, milestone)


def render_summary(specs):
    """Render the per-milestone progress list for ``docs/roadmap.adoc``."""
    progress = milestone_progress(specs)
    lines = []
    for milestone in sorted(progress, key=_milestone_order):
        done, total, verified, count = progress[milestone]
        label = "No milestone" if milestone == "None" else milestone
        lines.append(
            f"* {label}: {verified}/{count} specs verified; "
            f"{done}/{total} acceptance gates met"
        )
    return "\n".join(lines)


def _block(text, start, end):
    if start not in text or end not in text:
        return ""
    return text.split(start, 1)[1].split(end, 1)[0].strip("\n")


def _replace_block(text, start, end, content, label):
    if start not in text or end not in text:
        raise ValueError(f"roadmap.adoc is missing the {label} markers")
    head, rest = text.split(start, 1)
    return f"{head}{start}\n{content}\n{end}{rest.split(end, 1)[1]}"


def tracker_block(roadmap_text) -> str:
    """Return the tracker table between the markers, or '' when absent."""
    return _block(roadmap_text, _TABLE_START, _TABLE_END)


def tracker_summary_block(roadmap_text) -> str:
    """Return the milestone summary between the markers, or '' when absent."""
    return _block(roadmap_text, _SUMMARY_START, _SUMMARY_END)


def write_tracker(roadmap_text, specs) -> str:
    """Return ``roadmap_text`` with both generated blocks replaced."""
    text = _replace_block(
        roadmap_text, _TABLE_START, _TABLE_END, render_tracker(specs), "tracker table"
    )
    return _replace_block(
        text, _SUMMARY_START, _SUMMARY_END, render_summary(specs), "summary"
    )


def milestone_progress(specs):
    """Return ``{milestone: (done_gates, total_gates, verified_specs, specs)}``."""
    summary = {}
    for spec in specs:
        done, total, verified, count = summary.get(spec.milestone, (0, 0, 0, 0))
        summary[spec.milestone] = (
            done + spec.gates_done,
            total + len(spec.gates),
            verified + (1 if spec.status in COMPLETE_STATUSES else 0),
            count + 1,
        )
    return summary


def replace_spec(spec, **changes):
    """Return a copy of ``spec`` with some fields replaced (for contract tests)."""
    return dataclasses.replace(spec, **changes)
